import argparse
import os
from dataclasses import dataclass
from typing import Dict


HOMOLOGY_THRESHOLDS = (100, 90, 70, 50, 30)


@dataclass(frozen=True)
class DatasetConfig:
    name: str
    data_root: str
    fasta_files: Dict[str, str]

    @property
    def features_dir(self):
        return os.path.join(self.data_root, 'features')

    @property
    def processed_dir(self):
        return os.path.join(self.data_root, 'processed')

    def retrieval_dir(self, topk, strategy):
        return os.path.join(
            self.processed_dir,
            f'top{topk}',
            f'esm2_{strategy}',
        )


_DATASET_CONFIGS = {
    'phopt': DatasetConfig(
        name='phopt',
        data_root='data',
        fasta_files={
            'train': 'data/phopt_training.fasta',
            'valid': 'data/phopt_validation.fasta',
            'test': 'data/phopt_testing.fasta',
        },
    ),
    'dedup': DatasetConfig(
        name='dedup',
        data_root='dedup_data',
        fasta_files={
            'train': 'dedup_data/dedup/train.fasta',
            'valid': 'dedup_data/dedup/val.fasta',
            'test': 'dedup_data/dedup/test.fasta',
        },
    ),
}

for threshold in HOMOLOGY_THRESHOLDS:
    name = f'homology{threshold}'
    data_root = os.path.join('homology_data', f'identity{threshold}')
    _DATASET_CONFIGS[name] = DatasetConfig(
        name=name,
        data_root=data_root,
        fasta_files={
            split: os.path.join(data_root, f'{split}.fasta')
            for split in ('train', 'valid', 'test')
        },
    )


DATASET_CHOICES = tuple(_DATASET_CONFIGS)


def add_dataset_argument(parser: argparse.ArgumentParser):
    parser.add_argument(
        '--dataset',
        choices=DATASET_CHOICES,
        default='phopt',
        help=(
            'Dataset to prepare or train on. homology100 through homology30 '
            'are generated by build_homology_ladder.py (default: phopt)'
        ),
    )


def get_dataset_config(dataset: str):
    return _DATASET_CONFIGS[dataset]
